import { pathToFileURL } from 'node:url';
import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const packageEntry = process.env.PLAYWRIGHT_ENTRY || 'playwright';
const { chromium } = packageEntry.includes(':') ? await import(pathToFileURL(packageEntry).href) : await import(packageEntry);
const browser = await chromium.launch({headless: true, ...(process.env.CHROME_PATH ? {executablePath: process.env.CHROME_PATH} : {})});
const folder = 'artifacts/browser';
mkdirSync(folder, {recursive:true});
const page = await browser.newPage({viewport:{width:1440,height:1050},acceptDownloads:true});
const errors=[];
page.on('pageerror', error=>errors.push(error.message));
try {
  await page.goto(process.env.PREVIEW_URL || 'http://127.0.0.1:8765', {waitUntil:'networkidle'});
  assert.equal(await page.locator('#results-body tr').count(),6);
  const englishHeading=await page.locator('h1').textContent();
  await page.screenshot({path:`${folder}/desktop.png`});
  await page.locator('#company-search').fill('no-company-exists-5678');
  await page.locator('#empty-state').waitFor({state:'visible'});
  assert.equal(await page.locator('#results-body tr').count(),0);
  await page.locator('#reset-filters').click();
  assert.equal(await page.locator('#results-body tr').count(),6);
  await page.locator('#email-filter').check();
  assert.ok(await page.locator('#results-body tr').count()>0);
  await page.locator('#email-filter').uncheck();
  await page.locator('#toggle-json').click();
  assert.ok(JSON.parse(await page.locator('#json-preview-code').textContent()).length===6);
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download-csv').click();
  await (await downloadPromise).saveAs(`${folder}/sample.csv`);
  await page.locator('#website-input').fill('https://www.python.org/\nhttps://www.djangoproject.com/\nhttps://www.python.org/contact');
  await page.locator('#configuration-form button[type=submit]').click();
  const input=JSON.parse(await page.locator('#input-json').textContent());
  assert.equal(input.websites.length,2);
  assert.equal(input.respectRobots,true);
  await page.locator('#website-input').fill('http://127.0.0.1');
  await page.locator('#configuration-form button[type=submit]').click();
  assert.ok((await page.locator('#website-error').textContent()).trim());
  await page.locator('[data-language=vi]').click();
  assert.equal(await page.locator('html').getAttribute('lang'),'vi');
  assert.notEqual(await page.locator('h1').textContent(),englishHeading);
  await page.locator('[data-language=en]').click();
  await page.setViewportSize({width:390,height:844});
  await page.goto(process.env.PREVIEW_URL || 'http://127.0.0.1:8765', {waitUntil:'networkidle'});
  const sizes=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
  assert.ok(sizes.scroll<=sizes.viewport,JSON.stringify(sizes));
  await page.locator('#nav-toggle').click();
  assert.equal(await page.locator('#nav-toggle').getAttribute('aria-expanded'),'true');
  await page.locator('#nav-toggle').click();
  await page.screenshot({path:`${folder}/mobile.png`});
  assert.deepEqual(errors,[]);
  writeFileSync(`${folder}/report.json`,JSON.stringify({passed:true,checks:13,pageErrors:errors,mobileWidth:sizes.viewport},null,2));
  console.log(JSON.stringify({passed:true,checks:13,screenshots:[`${folder}/desktop.png`,`${folder}/mobile.png`]}));
} finally { await browser.close(); }
